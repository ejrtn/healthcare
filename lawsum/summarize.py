def strip_html(text):
    return re.sub(r"<[^>]+>", " ", text or "").strip()


def get_llm():
    # Kaggle GPU 실행(kaggle_summarize.py)은 이 파일의 프롬프트·후처리만 가져다 쓰므로 llama_cpp는 여기서만 불러온다
    from llama_cpp import Llama

    cpu_threads = os.cpu_count() or 4
    return Llama(
        model_path=MODEL_PATH,
        n_ctx=12288,  # 판례 최대 길이(14191자 사례 확인) 기준 여유 있게
        n_threads=cpu_threads,
        n_threads_batch=cpu_threads,
        n_gpu_layers=0,
        chat_format="llama-3",
        verbose=False,
    )


def _strip_lone_leading_number(text):
    """"1. ~"로 시작하는데 뒤에 "2." 같은 후속 번호가 없으면(쟁점이 하나뿐
    이라 번호를 매길 이유가 없으면) 앞의 "1." 표지만 지운다. 618229로
    실측하니 LLM이 원문의 "1." 표지를 그대로 복사해서 남겨뒀는데, 공식
    판결요지에는 쟁점이 하나뿐일 땐 그런 번호가 없었다 — 이것도 LLM
    지시로 맡기지 않고 코드로 결정적으로 처리한다."""
    m = re.match(r"^\s*\d+\.\s*", text)
    if not m:
        return text
    rest = text[m.end():]
    if re.search(r"(?:^|\n)\s*\d+\.\s", rest):
        return text  # 뒤에 2. 3. 등이 더 있으면(쟁점이 여럿) 번호를 유지
    return rest


# 처음엔 "관련 법리", "원심의 판단" 같은 알려진 제목 문구 목록으로
# 매칭을 시도했는데, "2. 공판준비기일에서의 증인신문 위법성에 관한 판단"
# 처럼 marker와 phrase 사이에 긴 수식어가 낀 경우를 놓쳤다. 그래서
# phrase 목록 대신 "제목처럼 생긴 것"을 구조로 정의했다 — marker 뒤에
# 마침표 없이 40자 이내로 끝나고 그 뒤에 큰 공백(원래 줄바꿈 자리)이
# 오면 제목으로 본다. 실제 법리 문장(보통 40자를 넘기거나 마침표로
# 끝남)은 이 조건에 안 걸려서 안전하다.
_HEADER_RE = re.compile(r"(?:\d+[.)]|[가-하][.)])\s*[^.!?]{1,40}?(?=\s{2,}|$)")


def _strip_section_headers(text):
    """"2. 공판준비기일에서의...판단", "가. 관련 법리", "다. 판단" 같은
    섹션 제목을 제거한다. 판결요지는 이런 제목 없이 쭉 이어지는 글이라는
    걸 62건 실측(섹션 제목 유무)과 사람이 직접 읽어본 결과(사용자 확인)로
    같이 확인했다. CLEANUP_PROMPT로 "소제목을 지우라"고 지시했지만
    LLM이 일관되게 못 지켜서(이 프로젝트에서 반복 확인된 패턴) 코드로
    옮겼다."""
    return _HEADER_RE.sub(" ", text).strip()


def _ask(llm, prompt, case_text):
    resp = llm.create_chat_completion(
        messages=[
            {"role": "system", "content": prompt},
            {"role": "user", "content": case_text},
        ],
        temperature=0.2,
        max_tokens=1500,
    )
    result = resp["choices"][0]["message"]["content"].strip()
    result = _strip_section_headers(result)
    return _strip_lone_leading_number(result)


# 1차 결과가 비정상적으로 짧을 때만 fallback을 쓰기 위한 기준.
# 정상적인 법리 발췌는 최소 한 문장(보통 수십~수백 자)인데, 618177/
# 240823의 실패 사례는 헤더 제거 후 0자였다 — 20자면 "제목 한 줄만
# 뱉었다"와 "실제 법리 문장을 가져왔다"를 안전하게 가른다.
_EMPTY_RESULT_THRESHOLD = 20


def summarize_case(llm, case_text):
    # 12차: extract_span.py(코드로 구간 자르기)를 거치지 않고, 판례내용
    # 전문을 그대로 넘긴다. 1차는 10차 프롬프트(법리만 긍정 정의,
    # 62건 평균 0.791)를 그대로 쓴다. 이 1차 결과가 거의 비었을 때만
    # (618177, 240823처럼 법리 단독 구간을 못 찾은 신호) 11차 프롬프트
    # (법리+적용)로 한 번 더 시도한다 — "법리+적용"을 전체 62건에 그대로
    # 적용하면 순수 법리형 판결요지 15건이 오히려 나빠지는 걸 실측으로
    # 확인했기 때문에, 영향 범위를 실패 사례로만 좁힌다.
    result = _ask(llm, SEMANTIC_PROMPT, case_text)
    if len(result) < _EMPTY_RESULT_THRESHOLD:
        result = _ask(llm, SEMANTIC_PROMPT_WITH_APPLICATION, case_text)
    return result


def main():
    with open("data/cases.json", encoding="utf-8") as f:
        cases = json.load(f)

    llm = get_llm()
    results = []
    for i, case in enumerate(cases, 1):
        content = strip_html(case.get("판례내용"))
        if not content:
            continue
        try:
            summary = summarize_case(llm, content)
            case["ai_summary"] = summary
            case["판결요지_clean"] = strip_html(case.get("판결요지"))
            results.append(case)
            print(f"[{i}/{len(cases)}] {case.get('사건명','')[:40]} -> 요약 완료 ({len(summary)}자)")
        except Exception as e:
            print(f"[{i}/{len(cases)}] 실패: {e}")

    with open("data/summarized.json", "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    print(f"\n완료: {len(results)}건 요약됨 -> data/summarized.json")


if __name__ == "__main__":
    main()
